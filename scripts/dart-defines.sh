# Sourced by the run scripts. DART_DEFINES holds a --dart-define for each
# allowed setting: from the environment when it's set there (scripts/deploy.sh
# sets the stage), otherwise from the repo's .env (see .env.example).
#
# Only the names below are passed: anything given to Flutter is compiled
# into the app (readable in the web bundle), so secrets in .env must never
# be listed here. Add public identifiers only: the API's URL and the Google
# OAuth client IDs are public (they're in every app that uses them).
_allowed=(GRIGRI_STAGE GRIGRI_API_URL GOOGLE_WEB_CLIENT_ID GOOGLE_IOS_CLIENT_ID)
_env="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/.env"
DART_DEFINES=()
for _name in "${_allowed[@]}"; do
  _value="${!_name:-}"
  if [[ -z "$_value" && -f "$_env" ]]; then
    _value="$(sed -n "s/^${_name}=//p" "$_env" | tail -1)"
  fi
  [[ -n "$_value" ]] && DART_DEFINES+=(--dart-define="${_name}=${_value}")
done

# iOS settings, written to a git-ignored xcconfig that Debug.xcconfig and
# Release.xcconfig include, so nothing personal or per-tenant is committed:
# - the developer's own signing team (IOS_DEVELOPMENT_TEAM in .env);
# - Google sign-in's iOS client ID and its reversed form, the URL scheme
#   Google redirects back to (Info.plist's GIDClientID and CFBundleURLTypes).
_ios="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/grigri_app/ios/Flutter/Private.xcconfig"
_setting() {
  local value="${!1:-}"
  [[ -z "$value" && -f "$_env" ]] && value="$(sed -n "s/^${1}=//p" "$_env" | tail -1)"
  printf '%s' "$value"
}
_team="$(_setting IOS_DEVELOPMENT_TEAM)"
_google_ios="$(_setting GOOGLE_IOS_CLIENT_ID)"
_lines=()
if [[ "$_team" =~ ^[A-Z0-9]{10}$ ]]; then
  _lines+=("DEVELOPMENT_TEAM=$_team")
elif [[ -n "$_team" ]]; then
  echo "warning: IOS_DEVELOPMENT_TEAM isn't a 10-character team ID; iOS stays unsigned" >&2
fi
if [[ "$_google_ios" =~ ^([A-Za-z0-9-]+)\.apps\.googleusercontent\.com$ ]]; then
  _lines+=("GOOGLE_IOS_CLIENT_ID=$_google_ios"
    "GOOGLE_IOS_URL_SCHEME=com.googleusercontent.apps.${BASH_REMATCH[1]}")
elif [[ -n "$_google_ios" ]]; then
  echo "warning: GOOGLE_IOS_CLIENT_ID isn't <id>.apps.googleusercontent.com; iOS can't sign in with Google" >&2
fi
if (( ${#_lines[@]} )); then
  { echo "// Generated by scripts/dart-defines.sh from .env; git-ignored."
    printf '%s\n' "${_lines[@]}"; } > "$_ios"
fi
unset _allowed _env _name _value _ios _team _google_ios _lines
unset -f _setting
